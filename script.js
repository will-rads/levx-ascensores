/* Floating navigation: one sliding highlight shared by hover and keyboard focus. */
const mainNav = document.querySelector(".main-nav");
const navLinks = [...mainNav.querySelectorAll("a")];
const navPill = mainNav.querySelector(".nav-pill");
let selectedNav = navLinks[0];
let previewNav = null;
function positionNavPill() {
  const link = previewNav || selectedNav;
  navPill.style.width = link.offsetWidth + "px";
  navPill.style.transform = `translateX(${link.offsetLeft}px)`;
  navPill.style.opacity = mainNav.offsetWidth ? 1 : 0;
  navLinks.forEach(a => a.classList.toggle("is-highlighted", a === link));
}
navLinks.forEach(link => {
  link.addEventListener("pointerenter", () => { previewNav = link; positionNavPill(); });
  link.addEventListener("focus", () => { previewNav = link; positionNavPill(); });
  link.addEventListener("click", () => { selectedNav = link; positionNavPill(); });
});
mainNav.addEventListener("pointerleave", () => {
  previewNav = navLinks.includes(document.activeElement) ? document.activeElement : null;
  positionNavPill();
});
mainNav.addEventListener("focusout", e => {
  previewNav = navLinks.includes(e.relatedTarget) ? e.relatedTarget : null;
  positionNavPill();
});
// ResizeObserver also catches language/font changes and desktop breakpoint entry.
new ResizeObserver(positionNavPill).observe(mainNav);
const navSections = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (!entry.isIntersecting) return;
    selectedNav = navLinks.find(link => link.hash === "#" + entry.target.id);
    navLinks.forEach(link => {
      if (link === selectedNav) link.setAttribute("aria-current", "location");
      else link.removeAttribute("aria-current");
    });
    positionNavPill();
  });
}, { rootMargin: "-68px 0px -60% 0px" });
navLinks.forEach(link => navSections.observe(document.querySelector(link.hash)));

/* Hero intro: the video is scrubbed by the scroll, the copy arrives when it ends.
   No scroll listener: a rAF loop runs only while the hero is on screen. */
const heroVideo = document.getElementById("heroVideo");
const heroCue = document.getElementById("heroCue");
const heroCopy = document.getElementById("heroCopy");
const noMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

if (noMotion) {
  hero.classList.add("no-scrub");
} else {
  const ramp = (a, b, p) => {
    const t = Math.min(Math.max((p - a) / (b - a), 0), 1);
    return t * t * (3 - 2 * t);
  };
  let running = false;
  let frame = 0;
  let lastSeek = -Infinity;
  let failed = false;

  function fallback() {
    failed = true;
    cancelAnimationFrame(frame);
    heroVideo.pause();
    hero.classList.add("no-scrub");
    heroCopy.style.opacity = 1;
    heroCopy.style.translate = "0 0";
    heroCopy.inert = false;
    clearTimeout(loadDeadline);
  }

  // Preload is only a hint on Safari. Briefly prime muted inline playback,
  // then keep playback paused: scrolling remains the only animation driver.
  function primeVideo() {
    if (failed || heroVideo.readyState >= 2) return;
    heroVideo.muted = true;
    const play = heroVideo.play();
    if (play) play.then(() => heroVideo.pause()).catch(() => {});
  }
  const loadDeadline = setTimeout(() => {
    if (heroVideo.readyState < 2) fallback();
  }, 15000);
  heroVideo.addEventListener("loadeddata", () => clearTimeout(loadDeadline), { once: true });
  heroVideo.addEventListener("error", fallback, { once: true });
  // A real gesture can unlock playback when automatic priming is blocked.
  window.addEventListener("touchstart", primeVideo, { once: true, passive: true });
  window.addEventListener("pointerdown", primeVideo, { once: true, passive: true });
  window.addEventListener("keydown", primeVideo, { once: true });
  primeVideo();

  function heroFrame(now) {
    frame = 0;
    if (!running || failed) return;
    const stage = hero.querySelector(".hero-stage");
    const travel = hero.offsetHeight - stage.offsetHeight;
    const p = travel > 0
      ? Math.min(Math.max(-hero.getBoundingClientRect().top / travel, 0), 1)
      : 1;
    const dur = heroVideo.duration;
    // One completed seek at a time, at most 24 per second for this 24fps clip.
    // Metadata is enough to seek; waiting for decoded data can stall Safari.
    if (Number.isFinite(dur) && dur > 0 && heroVideo.readyState >= 1 &&
        !heroVideo.seeking && now - lastSeek >= 1000 / 24) {
      const want = p * (dur - 0.06);
      if (Math.abs(want - heroVideo.currentTime) >= 1 / 48) {
        try {
          heroVideo.currentTime = want;
          lastSeek = now;
        } catch (_) { fallback(); return; }
      }
    }

    heroCue.style.opacity = 1 - ramp(0.56, 0.82, p);
    const shown = ramp(0.84, 1, p);
    heroCopy.style.opacity = shown;
    heroCopy.style.translate = "0 " + (1 - shown) * 20 + "px";
    heroCopy.inert = shown < 0.5;
    frame = requestAnimationFrame(heroFrame);
  }

  new IntersectionObserver(([e]) => {
    running = e.isIntersecting;
    if (running && !frame && !failed) frame = requestAnimationFrame(heroFrame);
    if (!running) { cancelAnimationFrame(frame); frame = 0; }
  }).observe(hero);
}

/* Service panels: expand on hover or click, drift on their own when left alone */
const panels = [...document.querySelectorAll(".panel")];
const panelBox = document.getElementById("panels");
const still = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
let panelTimer = null;

function openPanel(i) {
  panels.forEach((p, n) => {
    p.classList.toggle("is-open", n === i);
    p.setAttribute("aria-expanded", n === i ? "true" : "false");
  });
}

function panelDrift() {
  clearInterval(panelTimer);
  if (still) return;
  panelTimer = setInterval(() => {
    const at = panels.findIndex(p => p.classList.contains("is-open"));
    openPanel((at + 1) % panels.length);
  }, 7000);
}

panels.forEach((p, i) => {
  p.addEventListener("click", () => { openPanel(i); panelDrift(); });
  p.addEventListener("mouseenter", () => { openPanel(i); clearInterval(panelTimer); });
  p.addEventListener("focus", () => { openPanel(i); clearInterval(panelTimer); });
});
panelBox.addEventListener("mouseleave", panelDrift);
panelBox.addEventListener("focusout", e => {
  if (!panelBox.contains(e.relatedTarget)) panelDrift();
});

